import QRCode from "qrcode";
import Link from "next/link";
import { cancelMyTicket } from "@/app/actions";
import { ErrorBanner, SignInForm } from "@/app/components";
import { getCurrentBuyer, stateKey } from "@/lib/currentBuyer";
import { encodeTicketPass } from "@/lib/ticketPass";
import { formatPrice, formatWhen } from "@/lib/format";
import { getService } from "@/lib/store";

export const dynamic = "force-dynamic";

export default async function MyTickets({
  searchParams,
}: {
  searchParams: Promise<{ order?: string; confirm?: string; cancelled?: string; error?: string }>;
}) {
  const { order: justPaid, confirm, cancelled, error } = await searchParams;
  const buyer = await getCurrentBuyer();
  if (!buyer) {
    return (
      <>
        <h1>My tickets</h1>
        <SignInForm next="/tickets" />
      </>
    );
  }
  const svc = getService();
  const tickets = svc.ticketsFor(buyer.email);
  const withQr = await Promise.all(
    tickets.map(async (t) => {
      const pass = encodeTicketPass(svc.ticketSnapshot(t.id)!, stateKey());
      return {
        ...t,
        pass,
        canCancel: svc.canCancel(t.id),
        refund: svc.refundsFor(t.orderId).find((r) => r.ticketId === t.id),
        qrSvg: t.status === "void" ? "" : await QRCode.toString(pass, { type: "svg", margin: 1, width: 200 }),
      };
    }),
  );

  return (
    <>
      <h1>My tickets</h1>
      <p className="muted">
        Signed in as {buyer.name} ({buyer.email})
      </p>
      <ErrorBanner error={error} />
      {withQr.length === 0 && <p className="card">No tickets yet.</p>}
      <ul className="ticket-list">
        {withQr.map((t) => (
          <li key={t.id} className={`card ticket ${t.orderId === justPaid ? "fresh" : ""}`}>
            {t.orderId === justPaid && t.status === "valid" && <p className="success">Payment confirmed. Here is your ticket.</p>}
            {t.id === cancelled && t.refund && (
              <p className="success">Ticket cancelled. A full refund of {formatPrice(t.refund.amountCents)} was sent to your original payment method (simulated).</p>
            )}
            <p className="club">{t.event.clubName}</p>
            <h2>{t.event.title}</h2>
            <p className="muted">
              {formatWhen(t.event.startsAt)} · {t.event.venue}
            </p>
            {t.status === "void" ? (
              <p className="voided">QR code voided. This ticket will not be admitted.</p>
            ) : (
              /* SVG is generated by the qrcode library from our own signed ticket pass, not from user input. */
              <div className="qr" dangerouslySetInnerHTML={{ __html: t.qrSvg }} />
            )}
            <p className="small">
              Admit one: <strong>{t.buyerName}</strong> · {formatPrice(t.event.priceCents)} ·{" "}
              <span className={`status ${t.status}`}>{t.status}</span>
            </p>
            {t.status !== "void" && (
              <p className="token small muted">
                Ticket code (organizers paste this at the door) <code>{t.pass}</code>
              </p>
            )}
            {t.canCancel ? (
              confirm === t.id ? (
                <form action={cancelMyTicket} className="confirm">
                  <input type="hidden" name="ticketId" value={t.id} />
                  <p>Cancel this ticket and get a full refund of {formatPrice(t.event.priceCents)}? This cannot be undone.</p>
                  <button type="submit" className="button danger">
                    Yes, cancel and refund
                  </button>{" "}
                  <Link href="/tickets">Keep my ticket</Link>
                </form>
              ) : (
                <Link className="button secondary" href={`/tickets?confirm=${t.id}`}>
                  Cancel ticket
                </Link>
              )
            ) : (
              t.status === "valid" && (
                <p className="small muted">Cancellation closed: the event starts within 24 hours.</p>
              )
            )}
          </li>
        ))}
      </ul>
    </>
  );
}
